const KEYS = Object.keys(DICT).sort((a, b) => b.length - a.length);

function unique(items: string[]): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const item of items) {
    if (!item || seen.has(item)) continue;
    seen.add(item);
    out.push(item);
  }
  return out;
}

function greedy(reading: string): string {
  let i = 0;
  let out = "";
  while (i < reading.length) {
    let hit = "";
    let used = 0;
    for (const key of KEYS) {
      if (key.length > reading.length - i) continue;
      if (reading.startsWith(key, i)) {
        hit = DICT[key][0];
        used = key.length;
        break;
      }
    }
    if (!hit) {
      out += reading[i];
      i += 1;
    } else {
      out += hit;
      i += used;
    }
  }
  return out;
}

export function candidates(reading: string): string[] {
  const text = reading.trim();
  if (!text) return [];
  const phrase = lookupPhrase(text);
  const exact = DICT[text] ?? [];
  const compound = greedy(text);
  return unique([...(phrase ? [phrase.ja] : []), ...exact, compound, toKata(text), text]).slice(0, 8);
}

export function flushReading(pending: string): string {
  return commitKana(pending);
}
