const KATA_MAP = new Map<string, string>();
for (let i = 0; i < HIRA.length; i++) KATA_MAP.set(HIRA[i], KATA[i]);

export function toKata(text: string): string {
  return [...text].map((ch) => KATA_MAP.get(ch) ?? ch).join("");
}

